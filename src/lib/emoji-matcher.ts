function matchesKeyword(
  lowerSpaced: string,
  lowerNoSpace: string,
  keyword: string
): boolean {
  const kw = keyword.toLowerCase();
  if (/^[a-z0-9]+$/.test(kw)) {
    if (kw.length <= 4) {
      const boundaryRegex = new RegExp(`(^|[^a-z])${kw}($|[^a-z])`);
      return boundaryRegex.test(lowerSpaced);
    }
    return lowerNoSpace.includes(kw);
  }
  const kwNoSpace = kw.replace(/\s+/g, "");
  return lowerNoSpace.includes(kwNoSpace);
}

function hashLabel(input: string): number {
  let hash = 2166136261;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

export function matchWorkoutEmoji(
  label: string,
  existingCategories?: WorkoutCategoryMeta[]
): string {
  if (typeof label !== "string") {
    return "🏋️";
  }
  const trimmed = label.trim();
  if (!trimmed) {
    return "🏋️";
  }

  const lowerSpaced = trimmed.toLowerCase();
  const lowerNoSpace = lowerSpaced.replace(/[\s·ㆍ/,-]+/g, "");

  for (const rule of EMOJI_RULES) {
    for (const keyword of rule.keywords) {
      if (matchesKeyword(lowerSpaced, lowerNoSpace, keyword)) {
        return rule.emoji;
      }
    }
  }

  const usedEmojis = new Set(
    (existingCategories ?? []).map((item) => item.emoji)
  );
  const unusedPool = FALLBACK_EMOJIS.filter((emoji) => !usedEmojis.has(emoji));
  const pool = unusedPool.length > 0 ? unusedPool : FALLBACK_EMOJIS;
  const idx = hashLabel(lowerNoSpace || lowerSpaced) % pool.length;
  return pool[idx];
}
